package com.crnogorski.trener.data

import android.content.Context
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import kotlinx.serialization.json.Json

/**
 * Ударение в черногорском слове — но только там, где мы в нём уверены.
 *
 * Правило владельца: жирным выделяется ударная буква, а если уверенности нет,
 * слово остаётся как было. Поэтому здесь нет ни одной догадки — [of] отдаёт
 * `null` всюду, где ответ не следует из нормы или из словаря.
 *
 * Уверенность бывает двух родов.
 *
 * **Правило.** В штокавской норме нисходящие ударения стоят только на первом
 * слоге, а восходящие — на любом, кроме последнего. Отсюда следствие без
 * исключений: **на последний слог ударение не падает никогда**. Значит у слова
 * в один слог оно на единственном слоге, а у слова в два — на первом, и знать
 * тут больше нечего. В нашем словаре так закрывается 40% лемм, а с формами и
 * того больше: падежные окончания коротких слов слогов не добавляют.
 *
 * Правило проверено, а не принято на веру: `research/tools/fetch_stress.py`
 * сверил его с разметкой Викисловаря на всех одно- и двусложных словах
 * словаря и печатает расхождения. Их нет.
 *
 * **Словарь.** Для слов в три слога и длиннее место ударения не выводится
 * ниоткуда: `odgovárati` — третий слог, `poštòvati` — второй, `bubašvába` —
 * третий. Такие слова лежат в `assets/vocab/stress.json` — леммы, для которых
 * английский Викисловарь дал разметку, снятие знаков с которой даёт ровно наше
 * написание. Расхождения между вариантами внутри статьи в файл не попадают
 * вовсе: спорное — это и есть «не уверены».
 *
 * Чего тут нет намеренно:
 *
 * * **словоформ длиннее двух слогов.** Ударение при склонении переезжает и
 *   меняет тип (`vòda`, но `vȍdu` и `vódā`), так что метка леммы форме не
 *   годится. Короткие формы закрывает правило, длинные остаются без метки;
 * * **фраз.** В речи ударение уходит на проклитику (`ne znam` → `nè znām`,
 *   `u grad` → `ȕ grād`), поэтому слово внутри предложения размечать нельзя,
 *   даже когда само по себе оно размечено верно. [of] отдаёт `null` всему, где
 *   есть хоть один не-буквенный знак;
 * * **типа ударения.** Их четыре (краткое и долгое, восходящее и нисходящее),
 *   и жирная буква о них не говорит ничего. Это сознательное упрощение: место
 *   ударения русскому уху полезно и воспроизводимо, тон — нет.
 *
 * Считать слоги приложение обязано **точно так же**, как считает их скрипт: он
 * решает, для какого слова класть строку в файл, а приложение — у какого слова
 * спрашивать файл. Разойдись они, и приложение применяло бы правило там, где
 * скрипт правилу не доверился.
 */
object Stress {

    private const val PATH = "vocab/stress.json"
    private const val VOWELS = "aeiou"

    private val json = Json { ignoreUnknownKeys = true }

    /** Лемма → номер ударной буквы. Пустой словарь — просто нет меток. */
    private var lexicon: Map<String, Int> = emptyMap()

    /**
     * Прочитать файл ударений. Отсутствие или порча файла — не ошибка:
     * останутся метки по правилу, а слова длиннее двух слогов будут без них.
     */
    suspend fun load(context: Context) = withContext(Dispatchers.IO) {
        lexicon = runCatching {
            json.decodeFromString<Map<String, Int>>(
                context.assets.open(PATH).bufferedReader().use { it.readText() }
            )
        }.getOrDefault(emptyMap())
    }

    /**
     * Номер ударной буквы в слове или `null`, если мы не уверены.
     *
     * Индекс именно буквы, а не слога: выделять предстоит одну букву, и
     * пересчитывать слоги в буквы на экране незачем.
     */
    fun of(word: String): Int? {
        if (word.isEmpty() || !word.all { it.isLetter() }) return null
        val w = word.lowercase()
        val nuclei = nuclei(w)
        return when {
            nuclei.isEmpty() -> null
            nuclei.size <= 2 -> nuclei.first()
            else -> lexicon[w]
        }
    }

    /**
     * Слоговые вершины: гласные плюс слоговое `r` (`mŕžnja`, `pȑvi`).
     *
     * Слоговым `r` считается зажатое между согласными или стоящее с краю слова
     * рядом с согласной. Одинокое `r` вершиной не считается — слова из одной
     * буквы `r` в языке нет, а вот заглушка или обрывок строки быть может.
     */
    private fun nuclei(w: String): List<Int> = buildList {
        w.forEachIndexed { i, c ->
            val prev = w.getOrNull(i - 1)
            val next = w.getOrNull(i + 1)
            val vowel = c in VOWELS
            val syllabicR = c == 'r' &&
                prev?.let { it !in VOWELS } != false &&
                next?.let { it !in VOWELS } != false &&
                (prev != null || next != null)
            if (vowel || syllabicR) add(i)
        }
    }
}
