package com.crnogorski.trener.data

/**
 * Что сказать движку вместо написанного, когда он выговаривает слово неверно.
 *
 * Зеркальный близнец [Ijekavica]: тот меняет **показанное**, не трогая ключ
 * карточки, а этот меняет **произнесённое**, не трогая текст на экране.
 *
 * Зачем. Голос телефона (`sr-RS` от Google) коверкает два слова курса, и
 * найдено это стендом 25.09.2026: `sjutra` он произносит так, что чужое ухо
 * слышит «si utra», а собственный распознаватель телефона — сербское `sutra`
 * (десять случаев из одиннадцати за сентябрь); `nedjelju` он произносит
 * `nedelju`, три раза из трёх. Проверено чужим голосом: `bs-BA-GoranNeural`
 * говорит оба слова так, что Whisper пишет их дословно, — значит дело в голосе,
 * а не в привычках слушателя.
 *
 * Почему это надо чинить, хотя ничего не ломается. В заданиях «на слух» и в
 * `listening` текст закрыт, и синтезатор — **единственный** источник звука:
 * человек повторяет то, что услышал. Экран потом показывает черногорскую форму,
 * голос научил сербской, а проверка согласна с обеими — `LocalCheck.reflex`
 * сводит `sjutra` к `sutra` и `nedjelju` к `nedelju`. Помех занятию нет вовсе,
 * поэтому жалобы на это не будет никогда, и найти такое можно только прибором.
 *
 * Почему **карта**, а не правка текстов. `sjutra` — хорошее черногорское слово,
 * ровно то, чему курс учит; выкидывать его из заданий на слух из-за брака
 * чужого движка значит подгонять курс под движок. Экран остаётся правдой,
 * меняется только то, что уходит в синтезатор.
 *
 * **Живёт в `config/tuning.json`** (`speech.vygovor`), и это главное свойство:
 * написание подбирается опытом, а не выводится, и менять его придётся чаще, чем
 * собирать APK. Пустая карта в файле (`"vygovor": {}`) выключает приём целиком —
 * то есть откат не требует ни сборки, ни установки на три телефона.
 *
 * Чего карта не делает и делать не должна:
 *
 * * **не трогает показанное** — ни в задании, ни в эталоне, ни в подсказках.
 *   Иначе это была бы правка курса, а не произношения;
 * * **не участвует в сверке ответа.** Человек отвечает по тому, что слышал, а
 *   сверяется с текстом, и свёртка ятя обе формы и так приравнивает;
 * * **не растёт без опыта.** Запись сюда имеет смысл только после того, как
 *   написание проверено чужим ухом (`research/tools/vygovor.py` называет
 *   подозреваемых, `krug.py` и проба на телефоне выбирают замену).
 */
object Vygovor {

    /** Слова и знаки внутри слова: дефис в счёт, пробелы и запятые нет. */
    private val WORD = Regex("[\\p{L}\\p{M}-]+")

    private val map: Map<String, String>
        get() = Config.current.speech.vygovor

    /**
     * Заменить слова целиком, сохранив заглавную букву.
     *
     * **Словом целиком, а не подстрокой** — и это не придирка, а урок, за
     * который проект уже платил дважды: подстрочная замена `đe` → `gde`
     * калечит всякое слово, внутри которого сидит `đe`, а разбор иекавицы
     * 25.09.2026 той же ошибкой превратил `nedjelju` в `negdelju` и объявил,
     * что экавицы в корпусе нет вовсе.
     *
     * Заглавная сохраняется, потому что фразы начинаются с этих слов
     * («Sjutra idemo na plažu»), а движку регистр безразличен только на вид:
     * незнакомое написание с заглавной он читает иначе, чем со строчной.
     */
    fun say(text: String): String {
        val m = map
        if (m.isEmpty()) return text
        return WORD.replace(text) { found ->
            val word = found.value
            val to = m[word.lowercase()] ?: return@replace word
            if (word.first().isUpperCase() && to.isNotEmpty()) {
                to.replaceFirstChar { it.uppercaseChar() }
            } else {
                to
            }
        }
    }
}
