package com.crnogorski.trener.data

/**
 * Сербская кириллица → латиница.
 *
 * Нужно ради одного: Google Translate переводит с русского на **сербский**, а
 * сербский он отдаёт кириллицей. Курс же весь латиницей, и фраза, пришедшая
 * через «Поделиться», должна лечь в записи в том виде, в каком её потом учат.
 *
 * ## Почему это направление безопасно, а обратное нет
 *
 * Кириллица → латиница однозначна: каждой букве соответствует ровно одна
 * латинская запись, пусть иногда из двух знаков (`љ` → `lj`, `њ` → `nj`,
 * `џ` → `dž`). Обратное направление как раз опасно — там `nj` бывает и
 * двузнаком, и стыком двух букв (`injekcija` это и-н-ј, `nadživjeti` это д-ж),
 * и проект уже платил за это в разведке. Здесь такой беды нет по построению.
 *
 * ## Чего эта функция не делает и делать не должна
 *
 * **Экавицу в иекавицу не переводит.** Google отдаёт «Овде је лепо», то есть
 * `Ovde je lepo`, а курс говорит `Ovdje je lijepo` — но вывести это правилом
 * нельзя: не всякое «е» — ять (`pet`, `nebo`, `selo`, `sestra`). Именно поэтому
 * карта [Ijekavica] в проекте ручная, а свёртка [LocalCheck.reflex] работает
 * только в одну сторону. Значит письмо переводим, диалект оставляем как есть:
 * запись — это сырьё, а форму выберет человек, когда фраза пойдёт в урок.
 *
 * **Русский текст не трогает вовсе.** Если в тексте есть буквы, которых в
 * сербской азбуке нет (ы, э, ю, я, ё, й, щ, ъ, ь), это русская сторона перевода,
 * и переводить её в латиницу значило бы получить «privet» вместо «привет».
 * Русская фраза в записях уместна не меньше черногорской: «мои фразы» — это
 * часто ровно то, что понадобилось сказать, а нечем.
 *
 * Остаётся редкий случай: русская фраза, целиком набранная общими буквами
 * («он дома»). Её отличить нечем, и она переведётся в «on doma» — поэтому
 * результат показывается человеку до записи, а не сохраняется молча.
 */
object Cirilica {

    /** Буквы, которых в сербской азбуке нет вовсе: по ним виден русский текст. */
    private const val RUSSIAN = "ыэюяёйщъьЫЭЮЯЁЙЩЪЬ"

    /**
     * Строчные буквы сербской азбуки. Прописные получаются отсюда же: у
     * однознака первая буква поднимается, у двузнака — см. [latin].
     */
    private val LETTERS = mapOf(
        'а' to "a", 'б' to "b", 'в' to "v", 'г' to "g", 'д' to "d",
        'ђ' to "đ", 'е' to "e", 'ж' to "ž", 'з' to "z", 'и' to "i",
        'ј' to "j", 'к' to "k", 'л' to "l", 'љ' to "lj", 'м' to "m",
        'н' to "n", 'њ' to "nj", 'о' to "o", 'п' to "p", 'р' to "r",
        'с' to "s", 'т' to "t", 'ћ' to "ć", 'у' to "u", 'ф' to "f",
        'х' to "h", 'ц' to "c", 'ч' to "č", 'џ' to "dž", 'ш' to "š"
    )

    /** Есть ли в тексте кириллица вообще — по этому решается, надо ли переводить. */
    fun hasCyrillic(text: String): Boolean =
        text.any { it.lowercaseChar() in LETTERS || it in RUSSIAN }

    /** Похоже ли на сербский: кириллица есть, а чисто русских букв нет. */
    fun serbian(text: String): Boolean =
        hasCyrillic(text) && text.none { it in RUSSIAN }

    /**
     * Перевод в латиницу. Не сербская кириллица возвращается как была — решает
     * это [serbian], а не эта функция: молча портить русский текст хуже, чем
     * не тронуть его вовсе.
     */
    fun latin(text: String): String {
        if (!serbian(text)) return text
        val out = StringBuilder(text.length + 8)
        text.forEachIndexed { i, ch ->
            val letter = LETTERS[ch.lowercaseChar()]
            if (letter == null) {
                out.append(ch)
                return@forEachIndexed
            }
            if (!ch.isUpperCase()) {
                out.append(letter)
                return@forEachIndexed
            }
            // Прописной двузнак пишется двумя способами, и выбор виден только
            // по соседу: «Његош» → «Njegoš», но «ЊЕГОШ» → «NJEGOŠ».
            val shouting = text.getOrNull(i + 1)?.isUpperCase() == true
            out.append(
                if (letter.length > 1 && shouting) letter.uppercase()
                else letter.replaceFirstChar { it.uppercaseChar() }
            )
        }
        return out.toString()
    }
}
