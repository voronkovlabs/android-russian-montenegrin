package com.crnogorski.trener.data

/**
 * Леммы, которых в курсе быть не должно, — словарь их больше не показывает.
 *
 * Заведено по жалобе Кати (issue 79): «Никогда не слышала, чтобы местные
 * использовали это слово. Лучше его убрать из курса» — про `ala`, стоявшее
 * **седьмым** словом словаря.
 *
 * ## Почему список, а не кнопка у человека
 *
 * Мы уже умеем откладывать слово на две недели (`AppViewModel.snoozeCurrent`),
 * и напрашивалось усилить эту кнопку до «никогда». Но случай другой: `ala`
 * сломана **одинаково для всех троих**, и персональный список означал бы, что
 * каждый натыкается на неё сам и выбрасывает сам. Это не вкус, а брак данных,
 * и убирать его надо там же, где собирают словарь.
 *
 * Кнопка «отложить» при этом остаётся и решает своё: «мне не нужен снегопад
 * прямо сейчас» — это про человека, а не про слово.
 *
 * ## Почему лемма остаётся в словаре
 *
 * Выбросить её из `words.json` было бы честнее всего и нельзя: `build_vocab`
 * держит гарантию «словарь только растёт», а сборка сравнивает списки и
 * поднимает крик на любой потере. Гарантия эта дороже: она защищает от тихой
 * пропажи прогресса, ради которой и заведена. Поэтому лемма лежит на месте, а
 * приложение её не берёт.
 *
 * ## Чем это платится
 *
 * У того, кто слово уже проходил, карточки остаются в базе сиротами: заданий
 * по ним больше не построить, а `vocabDue` считает по таблице и держал бы их в
 * «просрочено» вечно. Поэтому сироты вычищаются один раз при запуске
 * (`AppViewModel.dropExcluded`). Прогресс по выброшенному слову теряется — он
 * тут и не прогресс, а след от брака.
 *
 * ## Что сюда попадает
 *
 * **Битые записи.** У `ala` частота набрана чужим словом: srLex засчитал ей
 * форму `ali` («но», полтора миллиона вхождений против собственных 2583), и
 * оба примера в карточке — про «но». Толкование при этом от третьего слова,
 * междометия («Ala je lijepo!»), хотя часть речи — существительное, а
 * существительное `ala` значит «дракон». Три разных слова в одной карточке.
 *
 * `bilo` и `bit` — та же болезнь: оба набрали место в первой тридцатке на
 * формах глагола `biti` («было», «bit ću»), а толкования у них от
 * существительных-омонимов — «было» вместо «пульса» и «комп. бит».
 *
 * **Непечатное.** `jebati` стояло 204-м и дошло бы до карточки за месяц.
 * Фильтр `RUDE` в `build_vocab` их не поймал: он смотрит на текст толкования,
 * а помета «обсц.» стоит перед словом и часть списка прошла мимо. Курс учат
 * трое, включая тринадцатилетнего.
 *
 * Список ручной и короткий намеренно. Он не средство чистить словарь от
 * редкого или скучного — для этого есть «отложить на потом»; сюда попадает
 * только то, чему карточка **научить не может**.
 */
object Excluded {

    /** Брать ли слово в курс вообще. */
    fun allows(lemma: String): Boolean = lemma !in LEMMAS

    val LEMMAS: Set<String> = setOf(
        // частота от чужого слова, толкование от третьего
        "ala",
        // формы `biti`, а толкования от существительных-омонимов
        "bilo",
        "bit",
        // непечатное
        "jebati",
        "kurac",
        "pizda",
    )
}
