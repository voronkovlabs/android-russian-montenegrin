package com.crnogorski.trener.data

/**
 * Когда человек последний раз что-то трогал — и сколько времени он не трогал
 * ничего.
 *
 * Заведено по жалобам 116 и 121: «если урок или стория просто открыты и ничего
 * не происходит секунд 10, то дальнейшее время не засчитывается… можно просто
 * открыть, оставить на 15 минут и получится, что типа позанимался».
 *
 * Дело не в жульничестве — своих трое, и обманывать себя им незачем. Дело в
 * том, что **«секунды на ответ» в отчёте — единственное число, которое мерит
 * беглость**, а отвлечение, посчитанное занятием, его портит молча.
 *
 * Частично это уже было прикрыто: дольше `Pace.SAMPLE_MAX` (полторы минуты) на
 * одно задание не списывается никогда. То есть уйти на пятнадцать минут и
 * получить пятнадцать было нельзя и раньше — но полторы минуты незаработанного
 * на каждом задании оставались, а на показе парадигмы, который ничего не
 * спрашивает, это особенно заметно.
 *
 * ## Что считается касанием
 *
 * Любое событие указателя на экране — нажатие, прокрутка, перетаскивание, — и
 * **отдельно набор текста**. Второе обязательно: клавиатура живёт своим окном,
 * её нажатия до нас не доходят вовсе, и человек, старательно печатающий ответ
 * сорок секунд, иначе оказался бы «отсутствующим».
 *
 * ## Что вычитается
 *
 * Промежуток без касаний **сверх порога**, а не целиком. Порог (`daily.idleSeconds`,
 * по умолчанию десять) — это столько тишины, сколько прощается на подумать:
 * над переводом действительно думают молча. Всё, что дольше, отличить от
 * телефона на столе нечем, и оно не засчитывается.
 *
 * Иначе говоря, за одно необъяснённое молчание мы платим не больше порога,
 * сколько бы оно ни длилось.
 *
 * ## Почему промежутки, а не отметка у задания
 *
 * Напрашивалось положить «сколько было простоя к началу задания» в
 * `SessionState` рядом с `shownAt`. Но `shownAt` выставляется в восьми местах,
 * и девятое однажды забыли бы — а забытое здесь выглядит не как поломка, а как
 * честное число. Поэтому простой копится сам, отдельно, и спрашивают его по
 * времени начала: [idleSince].
 *
 * Кольцо на [KEEP] промежутков: простоев за занятие бывает единицы, а хранить
 * их вечно незачем.
 */
object Touch {

    private const val KEEP = 64

    /** Промежутки без касаний: пара «с какого момента по какой», стенные часы. */
    private val gaps = ArrayDeque<LongArray>()

    private var lastAt = 0L

    /** Порог тишины: столько прощается на подумать. */
    private val limitMs: Long get() = Config.current.daily.idleSeconds * 1000L

    /**
     * Человек что-то тронул.
     *
     * Зовётся из одного места на весь экран (перехват событий указателя в
     * `MainActivity`) и из полей ввода — см. выше, почему второе обязательно.
     */
    fun note() {
        val now = System.currentTimeMillis()
        val was = lastAt
        lastAt = now
        if (was == 0L) return
        val limit = limitMs
        val gap = now - was
        if (gap <= limit) return
        synchronized(gaps) {
            // Начало промежутка — не сам момент прошлого касания, а порог
            // после него: первые секунды тишины засчитываются как раздумье.
            gaps.addLast(longArrayOf(was + limit, now))
            while (gaps.size > KEEP) gaps.removeFirst()
        }
    }

    /**
     * Сколько секунд с момента [from] прошло без единого касания.
     *
     * Промежуток попадает в счёт только **закрытым**, то есть когда касание
     * уже случилось. Незакрытый — это тот, в котором мы находимся прямо
     * сейчас, а раз так, то и отвечать ещё некому: измерять нечего.
     */
    fun idleSince(from: Long): Int {
        if (from <= 0L) return 0
        var sum = 0L
        synchronized(gaps) {
            for (gap in gaps) {
                val from0 = maxOf(gap[0], from)
                if (gap[1] > from0) sum += gap[1] - from0
            }
        }
        return (sum / 1000L).toInt()
    }
}
